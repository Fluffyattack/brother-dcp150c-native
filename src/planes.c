typedef struct {
    uint8_t *bytes;
    size_t length, capacity, position, leading, horizontal_offset_bytes;
} RasterPassBuffer;

struct Bh7Planes {
    Bh7PlanesConfig configuration;
    Bh7PlanesWrite write;
    void *opaque;
    RasterPassBuffer pass_buffers[MAX_PASSES];
    RasterPassBuffer deferred;
    const PrintheadSchedule *profile;
    Bh7RowsBand band;
    size_t band_index, band_count, final_rows;
    size_t plane_bytes, plane_stride;
    size_t first_column, last_column;
    size_t current_printhead_pass, rows_in_current_pass;
    unsigned raster_group_phase, color_state;
    uint16_t raster_mode_word;
    uint8_t current_mode, output_flags;
    uint32_t paper_feed_units_24000;
    bool begun, failed;
};

static int reserve_pass_buffer_space(RasterPassBuffer *buffer, size_t additional)
{
    if (additional > SIZE_MAX - buffer->length)
        return -1;
    size_t needed = buffer->length + additional;
    if (needed <= buffer->capacity)
        return 0;
    size_t capacity = buffer->capacity ? buffer->capacity : 4096;
    while (capacity < needed) {
        if (capacity > SIZE_MAX / 2)
            return -1;
        capacity *= 2;
    }
    uint8_t *bytes = realloc(buffer->bytes, capacity);
    if (bytes == NULL)
        return -1;
    buffer->bytes = bytes;
    buffer->capacity = capacity;
    return 0;
}

static int append_bytes_to_pass_buffer(RasterPassBuffer *buffer, const uint8_t *bytes, size_t length)
{
    if (reserve_pass_buffer_space(buffer, length) < 0)
        return -1;
    if (length)
        memcpy(buffer->bytes + buffer->length, bytes, length);
    buffer->length += length;
    return 0;
}

static int write_output_bytes(Bh7Planes *planes, const uint8_t *bytes, size_t length)
{
    if (planes->failed)
        return -1;
    if (planes->output_flags & 2U) {
        if (append_bytes_to_pass_buffer(&planes->deferred, bytes, length) < 0)
            planes->failed = true;
    } else if (length && planes->write(planes->opaque, bytes, length) != 0) {
        planes->failed = true;
    }
    return planes->failed ? -1 : 0;
}

static int write_blank_plane_markers(Bh7Planes *planes, size_t count)
{
    uint8_t blanks[256];
    memset(blanks, 0x5a, sizeof blanks);
    while (count) {
        size_t part = count < sizeof blanks ? count : sizeof blanks;
        if (write_output_bytes(planes, blanks, part) < 0)
            return -1;
        count -= part;
    }
    return 0;
}

static int write_paper_feed_command(Bh7Planes *planes, uint32_t amount)
{
    const uint8_t full[3] = {'F', 0xff, 0x7f};
    while (amount >= 32767) {
        if (write_output_bytes(planes, full, 3) < 0)
            return -1;
        amount -= 32767;
    }
    const uint8_t remainder[3] = {'F', (uint8_t)amount, (uint8_t)(amount >> 8)};
    return write_output_bytes(planes, remainder, 3);
}

static void update_output_deferral_after_feed(Bh7Planes *planes)
{
    if ((planes->output_flags & 1U) && !(planes->output_flags & 2U)) {
        planes->output_flags |= 2U;
    } else if ((planes->output_flags & 0x30U) == 0x10U) {
        const uint8_t trigger = 't';
        planes->output_flags |= 0x40U;
        (void)write_output_bytes(planes, &trigger, 1);
        planes->output_flags = (uint8_t)((planes->output_flags & ~0x40U) | 0x20U);
    }
}

static void clear_printhead_pass(RasterPassBuffer *pass)
{
    pass->length = 0;
    pass->position = 0;
    pass->leading = 0;
    pass->horizontal_offset_bytes = 0;
}

static bool pass_contains_printable_payload(const RasterPassBuffer *pass)
{
    if (pass->length > 376)
        return true;
    for (size_t index = 0; index < pass->length; index++)
        if (pass->bytes[index] != 0x5a)
            return true;
    return false;
}

static int append_blank_plane_markers(RasterPassBuffer *pass, size_t count)
{
    if (!pass->length) {
        if (count > SIZE_MAX - pass->leading)
            return -1;
        pass->leading += count;
        return 0;
    }
    if (reserve_pass_buffer_space(pass, count) < 0)
        return -1;
    memset(pass->bytes + pass->length, 0x5a, count);
    pass->length += count;
    return 0;
}

static const PrintheadSchedule *find_printhead_schedule(uint16_t mode, uint8_t head)
{
    for (size_t index = 0; index < sizeof(printhead_schedules) / sizeof(printhead_schedules[0]); index++) {
        const PrintheadSchedule *profile = &printhead_schedules[index];
        if (profile->head_mode_selector == (mode & 0x30U) &&
            profile->resolution == (mode & 0xf00U) && profile->head == (head & 0x7fU))
            return profile;
    }
    return &printhead_schedules[0];
}

static unsigned horizontal_raster_repeat(uint16_t mode)
{
    switch (mode & 0xfffU) {
    case 0x106: return 3;
    case 0x107: case 0x505: case 0x515: case 0x525: return 4;
    case 0x105: case 0x205: case 0x215: case 0x500: case 0x510: case 0x520:
    case 0x600: case 0x610: case 0x620: case 0x700: case 0x710: case 0x720: return 2;
    default: return 1;
    }
}

static bool uses_high_resolution_scratch(uint16_t mode)
{
    switch (mode & 0xfffU) {
    case 0x500: case 0x505: case 0x510: case 0x515: case 0x520: case 0x525:
    case 0x600: case 0x610: case 0x620: case 0x700: case 0x710: case 0x720: return true;
    default: return false;
    }
}

static bool uses_all_four_ink_channels(const Bh7Planes *planes)
{
    return !(planes->raster_mode_word & 0x5000U) || (planes->raster_mode_word & 0x5000U) == 0x5000U;
}

static uint8_t select_initial_raster_mode(uint16_t mode)
{
    if (mode & 0x2000U)
        return (mode & 0x5000U) == 0x1000U ? 0x30 : 0x31;
    return (mode & 0x5000U) == 0x1000U ? 0 : 0x10;
}

static int write_raster_mode_command(Bh7Planes *planes, uint8_t mode)
{
    const uint8_t bytes[2] = {'I', mode};
    planes->current_mode = mode;
    return write_output_bytes(planes, bytes, 2);
}

static int write_framed_raster_segment(Bh7Planes *planes, RasterPassBuffer *pass, size_t leading, size_t trailing)
{
    if (leading > UINT32_MAX || trailing > UINT32_MAX ||
        pass->length > UINT32_MAX - leading ||
        trailing > UINT32_MAX - leading - pass->length)
        return -1;
    size_t total = pass->length + leading + trailing;
    uint16_t position = (uint16_t)(pass->horizontal_offset_bytes << 3);
    const uint8_t header[10] = {0x69, 0xe1, 'r', (uint8_t)position,
        (uint8_t)(position >> 8), 'L', (uint8_t)total, (uint8_t)(total >> 8),
        (uint8_t)(total >> 16), (uint8_t)(total >> 24)};
    if (write_output_bytes(planes, header, sizeof header) < 0 || write_blank_plane_markers(planes, leading) < 0 ||
        write_output_bytes(planes, pass->bytes, pass->length) < 0 || write_blank_plane_markers(planes, trailing) < 0)
        return -1;
    return 0;
}

static int write_next_printhead_pass(Bh7Planes *planes)
{
    const PrintheadSchedule *profile = planes->profile;
    size_t slot = (planes->current_printhead_pass + 1) % profile->pass_buffer_count;
    RasterPassBuffer *pass = &planes->pass_buffers[slot];
    uint32_t amount = profile->rows_per_pass[planes->current_printhead_pass] * profile->feed_step_units_24000;
    if (write_paper_feed_command(planes, amount) < 0)
        return -1;
    planes->paper_feed_units_24000 += amount;
    if (pass_contains_printable_payload(pass)) {
        size_t end = profile->nozzle_row_count * (uses_all_four_ink_channels(planes) ? 4U : 1U);
        if (pass->position > end ||
            write_framed_raster_segment(planes, pass, pass->leading, end - pass->position) < 0)
            return -1;
    }
    planes->current_printhead_pass = (planes->current_printhead_pass + 1) % profile->pass_buffer_count;
    planes->rows_in_current_pass = 0;
    clear_printhead_pass(pass);
    if (planes->paper_feed_units_24000 > planes->configuration.feed_limit)
        update_output_deferral_after_feed(planes);
    return planes->failed ? -1 : 0;
}

static int write_final_envelope_passes(Bh7Planes *planes)
{
    const PrintheadSchedule *profile = planes->profile;
    size_t channels = uses_all_four_ink_channels(planes) ? 4U : 1U;
    size_t saved_adjustment = 0;
    for (size_t offset = 0; offset < profile->pass_buffer_count; offset++) {
        size_t slot = (planes->current_printhead_pass + 1 + offset) % profile->pass_buffer_count;
        RasterPassBuffer *pass = &planes->pass_buffers[slot];
        size_t remaining = (uint16_t)(profile->nozzle_row_count * channels - pass->position);
        if (channels == 4)
            remaining >>= 2;
        uint32_t amount = profile->rows_per_pass[(planes->current_printhead_pass + offset) % profile->pass_buffer_count] *
                          profile->feed_step_units_24000;
        if (remaining * 160U <= amount) {
            saved_adjustment = remaining;
            amount -= (uint32_t)(remaining * 160U);
        }
        if (write_paper_feed_command(planes, amount) < 0)
            return -1;
        planes->paper_feed_units_24000 += amount;
        if (pass_contains_printable_payload(pass)) {
            size_t leading = (uint16_t)(pass->leading + saved_adjustment * channels);
            size_t trailing = (uint16_t)((profile->nozzle_row_count - saved_adjustment) * channels -
                                         pass->position);
            if (write_framed_raster_segment(planes, pass, leading, trailing) < 0)
                return -1;
        }
        clear_printhead_pass(pass);
        if (planes->paper_feed_units_24000 > planes->configuration.feed_limit)
            update_output_deferral_after_feed(planes);
    }
    return planes->failed ? -1 : 0;
}

static void apply_resolution_pass_mask(uint8_t *out, const uint8_t *in, size_t length,
                       uint16_t mode, unsigned phase)
{
    static const uint8_t fine_one[2] = {0xaa, 0x55};
    static const uint8_t fine_two[2] = {0xcc, 0x33};
    static const uint8_t highest_one[5] = {0x84, 0x21, 0x08, 0x42, 0x10};
    static const uint8_t highest_two[5] = {0xc0, 0x30, 0x0c, 0x03, 0};
    if ((mode & 0xf00U) == 0x600U) {
        uint8_t mask = (mode & 0x2000U) ? fine_two[phase & 1U] : fine_one[phase & 1U];
        for (size_t index = 0; index < length; index++)
            out[index] = in[index] & mask;
    } else if ((mode & 0xf00U) == 0x700U) {
        unsigned offset = (mode & 0x2000U) ? (phase % 5U) * 2U : phase % 5U;
        for (size_t index = 0; index < length; index++) {
            unsigned position = (unsigned)((offset + index) % 5U);
            out[index] = in[index] & ((mode & 0x2000U) ? highest_two[position] : highest_one[position]);
        }
    } else {
        memcpy(out, in, length);
    }
}

static int append_encoded_color_plane(Bh7Planes *planes, RasterPassBuffer *pass, const uint8_t *bytes,
                         bool content, unsigned mask_phase)
{
    if (!content)
        return append_blank_plane_markers(pass, 1);
    size_t nonzero = planes->plane_bytes;
    while (nonzero && bytes[nonzero - 1] == 0)
        nonzero--;
    size_t crop = planes->plane_bytes - nonzero;
    if (planes->current_mode > 0x2f)
        crop >>= 1;
    if (crop < pass->horizontal_offset_bytes)
        pass->horizontal_offset_bytes = crop;
    if (!nonzero)
        return append_blank_plane_markers(pass, 1);

    uint8_t masked[3088], transformed[3088], encoded[8192], framed[8195];
    if (planes->plane_bytes > sizeof masked)
        return -1;
    const uint8_t *input = bytes;
    if (planes->profile->mapping_group_count && (planes->raster_mode_word & 0xf00U) > 0x500U) {
        apply_resolution_pass_mask(masked, bytes, planes->plane_bytes, planes->raster_mode_word, mask_phase);
        input = masked;
    }
    size_t written = 0;
    unsigned flags = 0;
    int result;
    unsigned codec = planes->configuration.codec;
    if (planes->configuration.mirror && codec != 1) {
        if (dcp150c_reverse_pixels(input, planes->plane_bytes,
                                   (planes->raster_mode_word & 0x2000U) ? 2 : 1,
                                   transformed, sizeof transformed) != 0)
            return -1;
        input = transformed;
    }
    if (codec == 0) {
        memcpy(encoded, input, planes->plane_bytes);
        written = planes->plane_bytes;
        result = 0;
    } else if (codec == 2) {
        result = dcp150c_sparse_encode(input, planes->plane_bytes, encoded, sizeof encoded,
                                       &written, &flags);
    } else if (codec == 3) {
        result = dcp150c_quad_encode(input, planes->plane_bytes, encoded, sizeof encoded, &written);
    } else if (planes->configuration.mirror) {
        result = dcp150c_packbits_reverse_encode(input, planes->plane_bytes,
                                                 encoded, sizeof encoded, &written);
    } else {
        result = dcp150c_packbits_encode(input, planes->plane_bytes, encoded, sizeof encoded, &written);
    }
    if (result != 0)
        return -1;
    size_t framed_length;
    if (dcp150c_frame_block(encoded, written, flags, framed, sizeof framed, &framed_length) != 0)
        return -1;
    return append_bytes_to_pass_buffer(pass, framed, framed_length);
}

static int pad_pass_to_nozzle_position(RasterPassBuffer *pass, size_t position)
{
    if (position < pass->position || append_blank_plane_markers(pass, position - pass->position) < 0)
        return -1;
    pass->position = position;
    return 0;
}

static int append_raster_row_to_printhead_buffers(Bh7Planes *planes, const uint8_t *gray, bool content, unsigned phase)
{
    const PrintheadSchedule *profile = planes->profile;
    if (!profile->mapping_group_count) {
        RasterPassBuffer *pass = &planes->pass_buffers[0];
        if (uses_all_four_ink_channels(planes)) {
            if (!content) {
                if (append_blank_plane_markers(pass, 4) < 0)
                    return -1;
            } else {
                size_t nonzero[4], maximum = 0;
                for (size_t channel = 0; channel < 4; channel++) {
                    size_t count = planes->plane_bytes;
                    while (count && gray[channel * planes->plane_stride + count - 1] == 0)
                        count--;
                    nonzero[channel] = count;
                    if (count > maximum)
                        maximum = count;
                }
                size_t crop = planes->plane_bytes - maximum;
                if (planes->current_mode > 0x2f)
                    crop >>= 1;
                if (crop < pass->horizontal_offset_bytes)
                    pass->horizontal_offset_bytes = crop;
                if (!maximum) {
                    if (append_blank_plane_markers(pass, 4) < 0)
                        return -1;
                } else {
                    for (size_t channel = 0; channel < 4; channel++)
                        if (append_encoded_color_plane(planes, pass, gray + channel * planes->plane_stride,
                                         nonzero[channel] != 0, phase) < 0)
                            return -1;
                }
            }
            pass->position += 4;
        } else {
            if (append_encoded_color_plane(planes, pass, gray, content, phase) < 0)
                return -1;
            pass->position++;
        }
    } else {
        size_t group = planes->current_printhead_pass % profile->mapping_group_count;
        size_t group_base = profile->mapping_group_count * (planes->current_printhead_pass / profile->mapping_group_count);
        const NozzleRowSchedule *mapping = &profile->mapping[group][planes->rows_in_current_pass];
        RasterPassBuffer *first = &planes->pass_buffers[(mapping->color_buffer_index + group_base) % profile->pass_buffer_count];
        RasterPassBuffer *second = &planes->pass_buffers[(mapping->black_buffer_index + group_base) % profile->pass_buffer_count];
        if (uses_all_four_ink_channels(planes)) {
            if (pad_pass_to_nozzle_position(first, (size_t)mapping->color_nozzle_row * 4) < 0 ||
                pad_pass_to_nozzle_position(second, (size_t)mapping->black_nozzle_row * 4 + 3) < 0)
                return -1;
            for (size_t channel = 0; channel < 3; channel++)
                if (append_encoded_color_plane(planes, first, content ? gray + channel * planes->plane_stride : NULL,
                                 content, phase) < 0)
                    return -1;
            if (append_encoded_color_plane(planes, second, content ? gray + 3 * planes->plane_stride : NULL,
                             content, phase) < 0)
                return -1;
            first->position += 3;
            second->position++;
        } else {
            if (pad_pass_to_nozzle_position(second, mapping->black_nozzle_row) < 0 ||
                append_encoded_color_plane(planes, second, gray, content, phase) < 0)
                return -1;
            second->position++;
        }
    }
    return 0;
}

Bh7Planes *bh7_planes_create(const Bh7PlanesConfig *configuration,
                             Bh7PlanesWrite write, void *opaque)
{
    if (configuration == NULL || write == NULL || !configuration->feed_dpi)
        return NULL;
    Bh7Planes *planes = calloc(1, sizeof *planes);
    if (planes == NULL)
        return NULL;
    planes->configuration = *configuration;
    planes->write = write;
    planes->opaque = opaque;
    planes->raster_mode_word = configuration->mode_word;
    planes->current_mode = configuration->initial_mode;
    planes->output_flags = configuration->output_flags;
    planes->profile = find_printhead_schedule(planes->raster_mode_word, configuration->head_type);
    planes->raster_group_phase = 1;
    return planes;
}

void bh7_planes_destroy(Bh7Planes *planes)
{
    if (planes) {
        for (size_t index = 0; index < MAX_PASSES; index++)
            free(planes->pass_buffers[index].bytes);
        free(planes->deferred.bytes);
        free(planes);
    }
}

static int drain_deferred_output(Bh7Planes *planes, bool trigger)
{
    planes->output_flags = (uint8_t)(planes->output_flags & ~2U);
    if (trigger) {
        const uint8_t command = 't';
        if (write_output_bytes(planes, &command, 1) < 0)
            return -1;
    }
    if (planes->deferred.length &&
        planes->write(planes->opaque, planes->deferred.bytes, planes->deferred.length) != 0)
        return -1;
    planes->deferred.length = 0;
    return 0;
}

int bh7_planes_begin_page(Bh7Planes *planes, uint8_t initial, uint32_t feed_limit)
{
    if (!planes || planes->failed)
        return -1;
    if (planes->output_flags & 1U) {
        if (planes->output_flags & 4U)
            planes->output_flags = (uint8_t)(planes->output_flags & ~4U);
        else if (drain_deferred_output(planes, !(planes->output_flags & 8U)) < 0)
            return -1;
    }
    for (size_t index = 0; index < MAX_PASSES; index++)
        clear_printhead_pass(&planes->pass_buffers[index]);
    planes->configuration.feed_limit = feed_limit;
    planes->current_mode = initial;
    planes->raster_group_phase = 1;
    planes->current_printhead_pass = 0;
    planes->rows_in_current_pass = 0;
    planes->paper_feed_units_24000 = 0;
    planes->begun = false;
    return 0;
}

int bh7_planes_bounds(const Bh7RowsBand *band, bool rotated, Bh7PlanesBandInfo *information)
{
    if (!band || !information || !band->pixels || !band->rows || !band->columns ||
        band->columns > SIZE_MAX / 3 || band->row_stride < band->columns * 3 ||
        band->rows > SIZE_MAX / band->row_stride)
        return -1;
    memset(information, 0, sizeof *information);
    size_t first = rotated ? band->rows : band->columns;
    size_t last = 0;
    if (!rotated) {
        for (size_t column = 0; column + 1 < band->columns && first == band->columns; column++)
            for (size_t row = 0; row + 1 < band->rows; row++) {
                const uint8_t *pixel = band->pixels + row * band->row_stride + column * 3;
                if (pixel[0] != 255 || pixel[1] != 255 || pixel[2] != 255) {
                    first = column;
                    break;
                }
            }
        if (first < band->columns) {
            for (size_t remaining = band->columns; remaining && !last; remaining--) {
                if (remaining == band->columns - 1)
                    continue;
                size_t column = remaining - 1;
                for (size_t row = 0; row + 1 < band->rows; row++) {
                    const uint8_t *pixel = band->pixels + row * band->row_stride + column * 3;
                    if (pixel[0] != 255 || pixel[1] != 255 || pixel[2] != 255) {
                        last = remaining;
                        break;
                    }
                }
            }
        }
    } else {
        for (size_t row = 0; row < band->rows && first == band->rows; row++)
            for (size_t column = 0; column < band->columns; column++) {
                const uint8_t *pixel = band->pixels + row * band->row_stride + column * 3;
                if (pixel[0] != 255 || pixel[1] != 255 || pixel[2] != 255) {
                    first = row;
                    break;
                }
            }
        if (first < band->rows) {
            for (size_t remaining = band->rows; remaining && !last; remaining--) {
                const uint8_t *row = band->pixels + (remaining - 1) * band->row_stride;
                for (size_t column = 0; column < band->columns; column++) {
                    const uint8_t *pixel = row + column * 3;
                    if (pixel[0] != 255 || pixel[1] != 255 || pixel[2] != 255) {
                        last = remaining;
                        break;
                    }
                }
            }
        }
        size_t count = rotated ? band->rows : band->columns;
        size_t original_first = first;
        first = count - last;
        last = count - original_first;
    }
    information->has_content = last != 0;
    information->first_column = first;
    information->column_count = last >= first ? last - first : 0;
    return 0;
}

int bh7_planes_begin_band(Bh7Planes *planes, const Bh7RowsBand *band, size_t band_index,
                          size_t band_count, size_t final_rows, uint16_t effective_mode,
                          unsigned color_state, Bh7PlanesBandInfo *information)
{
    if (!planes || !band_count || band_index >= band_count || color_state < 1 || color_state > 2 ||
        bh7_planes_bounds(band, planes->configuration.rotated, information) < 0)
        return -1;
    planes->raster_mode_word = effective_mode;
    planes->color_state = color_state;
    planes->band = *band;
    planes->band_index = band_index;
    planes->band_count = band_count;
    planes->final_rows = final_rows;
    planes->first_column = information->first_column;
    planes->last_column = information->first_column + information->column_count;
    size_t width = planes->configuration.rotated ? band->rows : band->columns;
    size_t repeat = horizontal_raster_repeat(planes->raster_mode_word) * ((planes->raster_mode_word & 0x2000U) ? 2U : 1U);
    planes->plane_stride = uses_high_resolution_scratch(planes->raster_mode_word) ? 3088 : 1544;
    if (width > SIZE_MAX - 7 || (width + 7) / 8 > planes->plane_stride / repeat)
        return -1;
    planes->plane_bytes = ((width + 7) / 8) * repeat;
    planes->profile = find_printhead_schedule(planes->raster_mode_word, planes->configuration.head_type);
    planes->begun = true;
    information->plane_bytes = planes->plane_bytes;
    information->plane_stride = planes->plane_stride;
    return write_raster_mode_command(planes, select_initial_raster_mode(planes->raster_mode_word));
}

int bh7_planes_push(Bh7Planes *planes, const uint8_t *packed, size_t packed_size,
                    size_t input_rows, bool content)
{
    if (!planes || !planes->begun || planes->failed || input_rows > 16)
        return -1;
    unsigned resolution = planes->raster_mode_word & 0xf00U;
    size_t walks = input_rows;
    unsigned period = 1;
    if (resolution == 0x500U) walks *= 2;
    if (resolution == 0x600U) { walks *= 4; period = 2; }
    if (resolution == 0x700U) { walks *= 10; period = 5; }
    size_t maximum = uses_high_resolution_scratch(planes->raster_mode_word) ? (resolution == 0x700U ? 40 :
                     resolution == 0x500U ? 8 : 16) : 16;
    if (walks > maximum)
        walks = maximum;
    size_t gray_rows = (walks + period - 1) / period;
    size_t required = gray_rows * planes->plane_stride * 4;
    if (content && walks && (!packed || packed_size < required))
        return -1;

    if (planes->raster_group_phase == 1 && planes->band_index) {
        size_t rows = planes->configuration.rotated ? planes->band.columns : planes->band.rows;
        uint64_t target = rows * (uint64_t)(24000U / planes->configuration.feed_dpi) * planes->band_index;
        if (target > UINT32_MAX)
            return -1;
        if (planes->paper_feed_units_24000 < target) {
            if (target > planes->configuration.feed_limit)
                update_output_deferral_after_feed(planes);
            if (write_paper_feed_command(planes, (uint32_t)target - planes->paper_feed_units_24000) < 0)
                return -1;
            planes->paper_feed_units_24000 = (uint32_t)target;
        }
    }
    if (content) {
        uint8_t mode;
        if (planes->color_state == 1 || !(planes->raster_mode_word & 0x2000U))
            mode = uses_all_four_ink_channels(planes) ? 0x10 : 0;
        else
            mode = uses_all_four_ink_channels(planes) ? 0x31 : 0x30;
        if (mode != planes->current_mode && write_raster_mode_command(planes, mode) < 0)
            return -1;
    }
    if (planes->raster_group_phase == 1) {
        planes->rows_in_current_pass = 0;
        planes->current_printhead_pass = 0;
        uint16_t width = (uint16_t)planes->plane_bytes;
        const uint8_t command[3] = {'w', (uint8_t)width, (uint8_t)(width >> 8)};
        if (write_output_bytes(planes, command, 3) < 0)
            return -1;
    }
    size_t black_offset = (planes->raster_mode_word & 0x5000U) == 0x1000U ? planes->plane_stride * 3 : 0;
    for (size_t walk = 0; walk < walks; walk++) {
        const uint8_t *gray = content ? packed + (walk / period) * planes->plane_stride * 4 + black_offset : NULL;
        if (append_raster_row_to_printhead_buffers(planes, gray, content, (unsigned)(walk % period)) < 0)
            return -1;
        planes->rows_in_current_pass++;
        if (planes->rows_in_current_pass == planes->profile->rows_per_pass[planes->current_printhead_pass] && write_next_printhead_pass(planes) < 0)
            return -1;
    }
    planes->raster_group_phase = 0;
    return planes->failed ? -1 : 0;
}

int bh7_planes_end_band(Bh7Planes *planes, bool last)
{
    if (!planes || !planes->begun)
        return -1;
    if (last) {
        planes->raster_group_phase = 2;
        if (bh7_planes_push(planes, NULL, 0, 0, true) < 0)
            return -1;
        if (planes->configuration.head_type & 0x10U) {
            if (write_final_envelope_passes(planes) < 0)
                return -1;
        } else {
            for (size_t index = 0; index < planes->profile->pass_buffer_count; index++)
                if (write_next_printhead_pass(planes) < 0)
                    return -1;
        }
        planes->raster_group_phase = 1;
    }
    planes->begun = false;
    return 0;
}

int bh7_planes_end_page(Bh7Planes *planes)
{
    if (!planes || planes->failed)
        return -1;
    const uint8_t eject[2] = {0x0c, 0};
    if (write_output_bytes(planes, eject, (planes->output_flags & 2U) ? 2 : 1) < 0)
        return -1;
    return 0;
}

int bh7_planes_end_job(Bh7Planes *planes)
{
    if (!planes || planes->failed)
        return -1;
    if (planes->output_flags & 1U) {
        planes->output_flags |= 8U;
        if (drain_deferred_output(planes, false) < 0)
            return -1;
        planes->output_flags = (uint8_t)(planes->output_flags & 0xf6U);
    }
    return 0;
}
